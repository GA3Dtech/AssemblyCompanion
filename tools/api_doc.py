"""
tools/api_doc.py (Assembly Companion) - write docs/api.md, the reference of
the public API, from api.describe() (docstrings and signatures), so the
reference cannot drift from the code.

    python3 tools/api_doc.py           # rewrite docs/api.md
    python3 tools/api_doc.py --check   # exit 1 if docs/api.md is out of date

Runs with a plain Python: a minimal FreeCAD stand-in is installed when
FreeCAD is not importable (api.py only needs it at call time).
"""

import os
import sys
import types

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "api.md")
sys.path.insert(0, ROOT)

HEADER = """# Assembly Companion – public API

<!-- Generated by tools/api_doc.py from api.describe(): edit the docstrings
     in freecad/assembly_companion/api.py, then run the tool. -->

`freecad/assembly_companion/api.py` is the stable entry point for scripts,
agents and the FreeCAD MCP server. It is headless-safe (no dialog, no active
view), takes the document explicitly (object, internal name or label),
objects by internal name and files by path, and returns plain data accepted
by `json.dumps`. Functions that change a document accept `dry_run=True`.
Errors are the typed exceptions of `errors.py` (`AssemblyCompanionError`
and its subclasses `NoDocumentError`, `NoAssemblyError`,
`ObjectNotFoundError`, `UnsupportedObjectError`, `SourceNotFoundError`,
`GuiRequiredError`); each has `to_dict()`.

```python
from freecad.assembly_companion import api
api.describe()                    # this catalogue, as data
api.bom("Assembly")               # document by name, label or object
```

API version: **{version}** (incremented at every breaking change).

## Functions
"""


def _stub_freecad():
    try:
        import FreeCAD  # noqa: F401
        return
    except ImportError:
        pass

    class _Grp(object):
        def _get(self, key, default):
            return default
        GetBool = GetInt = GetFloat = GetString = _get

    fc = types.ModuleType("FreeCAD")
    fc.GuiUp = False
    fc.ParamGet = lambda path: _Grp()
    fc.Console = types.SimpleNamespace(PrintMessage=print, PrintWarning=print,
                                       PrintError=print, PrintLog=print)
    sys.modules["FreeCAD"] = fc


def render():
    _stub_freecad()
    from freecad.assembly_companion import api, i18n
    i18n._code = "en"            # English docstrings and messages
    info = api.describe()
    out = [HEADER.replace("{version}", str(info["api_version"]))]
    for f in info["functions"]:
        args = []
        for p in f["parameters"]:
            args.append(p["name"] if p["required"] else "%s=%r" % (p["name"], p["default"]))
        out.append("### `%s(%s)`\n\n%s\n" % (f["name"], ", ".join(args), f["doc"]))
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(DOC, encoding="utf-8") as fh:
                same = fh.read() == text
        except OSError:
            same = False
        if not same:
            print("docs/api.md is out of date: run python3 tools/api_doc.py")
            sys.exit(1)
        print("docs/api.md is up to date")
        return
    with open(DOC, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("docs/api.md written (%d functions)" % text.count("\n### "))


if __name__ == "__main__":
    main()
